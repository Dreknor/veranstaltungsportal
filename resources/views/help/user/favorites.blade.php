<x-help.article title="Favoriten & Merkliste" subtitle="Veranstaltungen als Favoriten speichern">
    <p>
        Speichern Sie interessante Veranstaltungen als Favoriten, um sie später schnell wiederzufinden.
    </p>

    <nav aria-label="Inhalt">
        <ul>
            <li><a href="#add">1. Favoriten hinzufügen</a></li>
            <li><a href="#manage">2. Favoriten verwalten</a></li>
        </ul>
    </nav>

    <section id="add">
        <h2>1. Favoriten hinzufügen</h2>

        <h3>Veranstaltung als Favorit markieren</h3>
        <ol>
            <li>Öffnen Sie die Detailseite einer Veranstaltung</li>
            <li>Klicken Sie auf das Herz-Symbol</li>
            <li>Die Veranstaltung ist jetzt gespeichert</li>
            <li>Sie finden sie unter <strong>Favoriten</strong></li>
        </ol>

        <ul>
            <li><strong>Favorit hinzufügen:</strong> Klick auf das leere Herz speichert die Veranstaltung</li>
            <li><strong>Favorit entfernen:</strong> Klick auf das gefüllte Herz entfernt die Veranstaltung</li>
        </ul>
    </section>

    <section id="manage">
        <h2>2. Favoriten verwalten</h2>

        <h3>Ihre Favoritenliste aufrufen</h3>
        <ol>
            <li>Klicken Sie in der Navigation auf <strong>Favoriten</strong></li>
            <li>Sie sehen alle gespeicherten Veranstaltungen als Liste</li>
        </ol>

        <h3>Favorit entfernen</h3>
        <p>
            Klicken Sie in der Liste bei der Veranstaltung auf <strong>„Aus Favoriten entfernen“</strong>.
        </p>
    </section>
</x-help.article>
