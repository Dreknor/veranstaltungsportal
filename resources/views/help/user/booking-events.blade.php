<x-help.article title="Veranstaltungen buchen" subtitle="So buchen Sie Tickets in wenigen Schritten">
    <section>
        <h2>Schritt-für-Schritt Anleitung</h2>

        <h3>1. Veranstaltung auswählen</h3>
        <p>Klicken Sie auf einer Veranstaltungsseite auf den Button <strong>„Buchen“</strong></p>
        <x-ui.alert tone="info" title="Veranstaltungen mit mehreren Terminen">Einige Veranstaltungen bestehen aus
            mehreren Terminen (z.B. ein 8-Wochen-Kurs). Bei diesen Veranstaltungen sehen Sie alle Termine aufgelistet.
            Die Buchung gilt automatisch für <strong>alle Termine</strong> - es ist nicht möglich, nur einzelne
            Termine zu buchen.</x-ui.alert>

        <h3>2. Ticket-Typ wählen</h3>
        <p>Wählen Sie den passenden Ticket-Typ (z.B. Standard, Ermäßigt, VIP) und die gewünschte Anzahl</p>
        <ul>
            <li>Prüfen Sie die Verfügbarkeit</li>
            <li>Beachten Sie eventuelle Limits pro Person</li>
        </ul>

        <h3>3. Rabattcode eingeben (optional)</h3>
        <p>Wenn Sie einen Rabattcode haben, geben Sie ihn ein und klicken Sie auf „Einlösen“</p>

        <h3>4. Persönliche Daten eingeben</h3>
        <p>Füllen Sie das Formular aus:</p>
        <ul>
            <li>Vor- und Nachname</li>
            <li>E-Mail-Adresse (für Bestätigung und Tickets)</li>
            <li>Telefonnummer (optional, aber empfohlen)</li>
            <li>Zusätzliche Informationen (falls vom Veranstalter gewünscht)</li>
        </ul>

        <h3>5. Buchung abschließen</h3>
        <p>Prüfen Sie alle Angaben und klicken Sie auf <strong>„Kostenpflichtig buchen“</strong> (bei kostenfreien
            Veranstaltungen <strong>„Verbindlich anmelden“</strong>)</p>

        <h3>6. Bestätigung erhalten</h3>
        <p>Sie erhalten sofort:</p>
        <ul>
            <li>Buchungsbestätigung per E-Mail</li>
            <li>Buchungsnummer zur Nachverfolgung</li>
            <li>Zahlungsinformationen (bei kostenpflichtigen Veranstaltungen)</li>
            <li>Tickets (nach Zahlungseingang)</li>
        </ul>
    </section>

    <section>
        <h2>Zahlungsarten</h2>
        <ul>
            <li><strong>Überweisung:</strong> Sie erhalten Bankdaten in der Bestätigung. Bitte als Verwendungszweck
                die Buchungsnummer angeben.</li>
            <li><strong>Kostenfreie Veranstaltungen:</strong> Bei kostenfreien Veranstaltungen erhalten Sie sofort
                Zugang und Tickets.</li>
        </ul>
    </section>

    <x-ui.alert tone="warning" title="Wichtig">Tickets für Präsenz-Veranstaltungen werden erst nach Zahlungseingang
        per E-Mail versendet. Zugangsdaten für Online-Veranstaltungen erhalten Sie ebenfalls nach Bezahlung.
    </x-ui.alert>
</x-help.article>
