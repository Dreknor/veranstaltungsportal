            </li>
            <li><strong>Marketing:</strong> Informationen über neue Features und Angebote</li>
        </ul>
    </section>

    <section id="gdpr">
        <h2>4. Ihre DSGVO-Rechte</h2>
        <p>Gemäß der Datenschutz-Grundverordnung (DSGVO) haben Sie folgende Rechte:</p>
        <ul>
            <li><strong>Recht auf Auskunft:</strong> Sie können jederzeit Auskunft über Ihre gespeicherten Daten
                erhalten.</li>
            <li><strong>Recht auf Berichtigung:</strong> Fehlerhafte Daten können Sie jederzeit in Ihren
                Einstellungen korrigieren.</li>
            <li><strong>Recht auf Löschung:</strong> Sie können Ihr Konto und alle Daten jederzeit löschen lassen.
            </li>
            <li><strong>Recht auf Datenübertragbarkeit:</strong> Exportieren Sie Ihre Daten in einem
                maschinenlesbaren Format.</li>
            <li><strong>Recht auf Widerspruch:</strong> Widersprechen Sie der Verarbeitung Ihrer Daten für bestimmte
                Zwecke.</li>
        </ul>

