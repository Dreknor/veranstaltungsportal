    <section>
        <h2>Buchungsübersicht</h2>
        <ul>
            <li><strong>Buchungsdetails ansehen:</strong> Klicken Sie unter „Meine Buchungen“ auf eine Buchung, um
                alle Details, Tickets und Dokumente zu sehen.</li>
            <li>
                <strong>Downloads:</strong>
                <ul>
                    <li>PDF-Ticket</li>
                    <li>Rechnung</li>
                    <li>Teilnahmezertifikat (nach der Veranstaltung)</li>
                    <li>Kalender-Datei (.ics)</li>
                </ul>
            </li>
        </ul>
    </section>

    <section>
        <h2>Buchung stornieren</h2>
        <ol>
            <li>Öffnen Sie die Buchungsdetails</li>
            <li>Klicken Sie auf „Buchung stornieren“</li>
            <li>Bestätigen Sie die Stornierung</li>
        </ol>
        <x-ui.alert tone="warning" title="Hinweis">Bitte beachten Sie die Stornierungsbedingungen des
            Veranstalters.</x-ui.alert>
    </section>

    <section>
        <h2>Zahlungsstatus</h2>
        <ul>
            <li><strong>Offen:</strong> Zahlung noch nicht eingegangen</li>
            <li><strong>Bezahlt:</strong> Zahlung bestätigt, Tickets verfügbar</li>
            <li><strong>Storniert:</strong> Buchung wurde storniert</li>
        </ul>
    </section>
