<x-help.article title="Häufig gestellte Fragen (FAQ)"
    subtitle="Antworten auf die wichtigsten Fragen zu Veranstaltungen mit mehreren Terminen">
    <section>
        <h2>Für Teilnehmer</h2>
        <details open>
            <summary>Was bedeutet "Veranstaltung mit mehreren Terminen"?</summary>
            <p>
                Eine Veranstaltung mit mehreren Terminen ist eine Veranstaltung, die aus mehreren aufeinanderfolgenden
                Terminen besteht,
                z.B. ein 8-Wochen-Yoga-Kurs oder ein 5-tägiger Workshop. Bei der Buchung erhalten Sie automatisch Zugang
                zu
                <strong>allen Terminen</strong> der Serie.
            </p>
        </details>

        <details>
            <summary>Kann ich nur einzelne Termine buchen?</summary>
            <p>
                Nein, bei Veranstaltungen mit mehreren Terminen ist das nicht möglich. Die Buchung gilt immer für alle
                Termine.
                Dies stellt sicher, dass alle Teilnehmer die komplette Serie besuchen können und z.B. bei Kursen
                der Lernfortschritt gewährleistet ist.
            </p>
        </details>

        <details>
            <summary>Wie erkenne ich, ob eine Veranstaltung mehrere Termine hat?</summary>
            <p>
                Auf der Veranstaltungsseite sehen Sie eine Liste aller Termine mit einem Badge "X Termine".
                Zusätzlich gibt es einen Hinweis, dass die Buchung für alle Termine gilt.
            </p>
        </details>

        <details>
            <summary>Was kostet die Teilnahme?</summary>
            <p>
                Der angezeigte Preis gilt für <strong>alle Termine zusammen</strong>, nicht pro Termin.
                Ein 8-Wochen-Kurs für 120€ bedeutet 120€ für die komplette Serie (alle 8 Termine).
            </p>
        </details>

        <details>
            <summary>Was passiert, wenn ein Termin ausfällt?</summary>
            <p>
                Wenn der Veranstalter einen einzelnen Termin absagen muss (z.B. wegen Krankheit), werden Sie per E-Mail
                informiert.
                Die anderen Termine finden normal statt. Der Veranstalter kann einen Nachholtermin anbieten oder den
                Termin später reaktivieren.
            </p>
        </details>

        <details>
            <summary>Was passiert, wenn ich einen Termin verpasse?</summary>
            <p>
                Ihre Buchung bleibt gültig und Sie können die anderen Termine besuchen.
                Kontaktieren Sie den Veranstalter, um ggf. Unterlagen oder Informationen zum verpassten Termin zu
                erhalten.
                Eine teilweise Rückerstattung ist normalerweise nicht möglich.
            </p>
        </details>

        <details>
            <summary>Kann ich stornieren?</summary>
            <p>
                Die Stornierungsbedingungen werden vom Veranstalter festgelegt. In der Regel können Sie bis 24 Stunden
                vor dem
                <strong>ersten Termin</strong> kostenlos stornieren. Bei einer Stornierung wird die gesamte Serie
                storniert,
                nicht nur einzelne Termine.
            </p>
        </details>

        <details>
            <summary>Wie erhalte ich meine Tickets?</summary>
            <p>
                Nach erfolgreicher Buchung und Bezahlung erhalten Sie per E-Mail Ihre Tickets.
                Das Ticket gilt für alle Termine der Serie. Sie müssen nicht für jeden Termin ein separates Ticket
                haben.
            </p>
        </details>

        <details>
            <summary>Finden alle Termine am gleichen Ort statt?</summary>
            <p>
                Normalerweise ja. In seltenen Fällen kann der Veranstalter für einzelne Termine einen abweichenden Ort
                angeben
                (z.B. Ausweichraum). Dies wird deutlich bei jedem Termin angezeigt.
            </p>
        </details>
    </section>

    <section>
        <h2>Für Veranstalter</h2>
        <details>
            <summary>Wann sollte ich "Veranstaltung mit mehreren Terminen" verwenden?</summary>
            <p>Verwenden Sie diese Option für:</p>
            <ul>
                <li>Kurse, die über mehrere Wochen gehen (z.B. 8-Wochen-Yoga-Kurs)</li>
                <li>Mehrtägige Workshops (z.B. 3-Tages-Seminar)</li>
                <li>Fortbildungsreihen mit mehreren Modulen</li>
                <li>Alle Veranstaltungen, bei denen Teilnehmer alle Termine besuchen sollen</li>
            </ul>
        </details>

        <details>
            <summary>Wie viele Termine kann ich erstellen?</summary>
            <p>
                Es gibt keine technische Begrenzung. Sie können beliebig viele Termine zu einem Veranstaltung
                hinzufügen.
                Für eine gute Übersichtlichkeit empfehlen wir jedoch maximal 20-30 Termine pro Veranstaltung.
            </p>
        </details>

        <details>
            <summary>Wie funktioniert die Kapazitätsverwaltung?</summary>
            <p>
                Die Kapazität (max. Teilnehmerzahl) gilt für die <strong>gesamte Serie</strong>.
                Wenn Sie 20 als Kapazität angeben, können maximal 20 Personen buchen und diese besuchen dann alle
                Termine.
                Es ist nicht "20 Plätze pro Termin".
            </p>
        </details>

        <details>
            <summary>Kann ich nachträglich Termine hinzufügen?</summary>
            <p>
                Ja, Sie können jederzeit weitere Termine hinzufügen, auch wenn bereits Buchungen vorliegen.
                Bereits gebuchte Teilnehmer werden automatisch für die neuen Termine registriert und sollten manuell
                informiert werden.
            </p>
        </details>

        <details>
            <summary>Was passiert, wenn ich einen Termin absage?</summary>
            <p>
                Klicken Sie beim betreffenden Termin auf "Absagen" und geben Sie einen Grund an.
                Alle gebuchten Teilnehmer werden automatisch per E-Mail informiert. Die Buchungen bleiben bestehen und
                die Teilnehmer können die anderen Termine besuchen. Sie können den Termin später reaktivieren oder einen
                Nachholtermin anlegen.
            </p>
        </details>

        <details>
            <summary>Kann ich für einzelne Termine unterschiedliche Preise festlegen?</summary>
            <p>
                Nein, es gibt einen Gesamtpreis für alle Termine. Dieser Preis wird bei der Buchung einmalig fällig.
                Wenn Sie unterschiedliche Preise pro Termin benötigen, sollten Sie separate Veranstaltungen erstellen.
            </p>
        </details>

        <details>
            <summary>Kann ich Ticket-Typen nutzen (z.B. Ermäßigung)?</summary>
            <p>
                Ja, Sie können verschiedene Ticket-Typen erstellen (z.B. Standard, Ermäßigt, VIP).
                Jeder Ticket-Typ gilt dann für alle Termine der Serie.
            </p>
        </details>

        <details>
            <summary>Wie kommuniziere ich mit Teilnehmern?</summary>
            <p>
                Nutzen Sie die Funktion "Teilnehmer kontaktieren" in der Veranstaltungsverwaltung, um E-Mails an alle
                gebuchten Teilnehmer zu senden (z.B. Erinnerungen, Materialinfos, Änderungen).
            </p>
        </details>

        <details>
            <summary>Kann ich zwischen normalen Veranstaltungen und Veranstaltungen mit mehreren Terminen wechseln?
            </summary>
            <p>
                Sie können die Option aktivieren/deaktivieren, solange keine Buchungen vorliegen.
                Nach der ersten Buchung ist eine Änderung nicht mehr möglich, um die Integrität der Buchungen zu
                gewährleisten.
            </p>
        </details>

        <details>
            <summary>Wie sieht die Teilnehmerliste aus?</summary>
            <p>
                Die Teilnehmerliste zeigt alle Personen, die die gesamte Serie gebucht haben.
                Sie können die Liste als Excel/CSV exportieren und für jeden Termin zur Anwesenheitskontrolle nutzen.
            </p>
        </details>
    </section>

