    <section>
        <h2>1. Featured Events – Hervorhebung</h2>
        <p>Markieren Sie Ihre Veranstaltung als „Featured" für maximale Sichtbarkeit:</p>
        <ul>
            <li>Featured Events erscheinen prominent auf der Startseite</li>
            <li>Eigene Sektion mit visueller Hervorhebung</li>
            <li>Höheres Ranking in Suchergebnissen</li>
            <li>Gebühr: täglich, wöchentlich oder monatlich buchbar</li>
        </ul>
        <p>Gehen Sie zu „Featured Events" › „Antrag stellen" und wählen Sie die Dauer. Nach Zahlung ist Ihre
            Veranstaltung sofort featured.</p>
    </section>

    <section>
        <h2>2. Social Media Sharing</h2>
        <p>Jede Veranstaltung hat Share-Buttons für:</p>
        <ul>
            <li><strong>Facebook:</strong> Teilen auf Ihrer Seite oder in Gruppen</li>
            <li><strong>Twitter/X:</strong> Tweet mit Veranstaltungslink</li>
            <li><strong>LinkedIn:</strong> Ideal für berufliche Fortbildungen</li>
            <li><strong>WhatsApp:</strong> Direkt an Kontakte oder Gruppen</li>
            <li><strong>E-Mail:</strong> Mailto-Link mit vorgefertigtem Text</li>
            <li><strong>Telegram:</strong> Teilen in Kanälen oder Gruppen</li>
        </ul>
        <p>Zusätzlich: „Link kopieren" für eigene Kanäle (Newsletter, Website, etc.)</p>
    </section>

    <section>
        <h2>3. SEO & Sichtbarkeit</h2>
        <p>Optimieren Sie Ihre Veranstaltung für Suchmaschinen:</p>
        <ul>
            <li><strong>Aussagekräftiger Titel:</strong> Inkl. relevanter Keywords</li>
            <li><strong>Detaillierte Beschreibung:</strong> Min. 200 Wörter, inkl. Lernziele</li>
            <li><strong>Kategorie korrekt wählen:</strong> Für bessere Auffindbarkeit</li>
            <li><strong>Bild hochladen:</strong> Ansprechendes Titelbild erhöht Klickrate</li>
        </ul>
        <p>Das System generiert automatisch Meta-Tags, Open Graph und strukturierte Daten (Schema.org).</p>
    </section>

    <section>
        <h2>4. Netzwerk & Empfehlungen</h2>
        <p>Nutzen Sie das Netzwerk der Plattform:</p>
        <ul>
            <li>Veranstaltungen werden Nutzern basierend auf ihren Interessen empfohlen</li>
            <li>Nutzer mit passenden Kategorien erhalten Benachrichtigungen bei neuen Veranstaltungen</li>
            <li>Favoriten-Funktion: Nutzer können Veranstaltungen merken und später buchen</li>
            <li>Bewertungen: Positive Reviews erhöhen Vertrauen und Sichtbarkeit</li>
        </ul>
    </section>

    <section>
        <h2>5. Rabattcodes für Marketing</h2>
        <p>Nutzen Sie Rabattcodes strategisch:</p>
        <ul>
            <li><strong>Partner-Codes:</strong> Für Kooperationen mit Schulen, Verbänden</li>
            <li><strong>Newsletter-Codes:</strong> Exklusive Rabatte für Abonnenten</li>
            <li><strong>Social-Media-Codes:</strong> Zeitlich begrenzte Aktionen</li>
            <li><strong>Tracking:</strong> Sehen Sie in der Statistik, welche Codes genutzt wurden</li>
        </ul>
    </section>

    <section>
        <h2>6. Eigene Marketing-Kanäle</h2>
        <p>Bewerben Sie Ihre Veranstaltung zusätzlich über:</p>
        <ul>
            <li>Ihre Website (iFrame-Einbettung oder direkter Link)</li>
            <li>Newsletter (Veranstaltungslink & Titelbild)</li>
            <li>Flyer & Poster (QR-Code mit Veranstaltungslink)</li>
            <li>Lokale Medien & Bildungsportale</li>
        </ul>
    </section>

    <x-ui.alert tone="info" title="Tipp">Kombinieren Sie Frühbucher-Rabatt mit Social-Media-Kampagne
        für maximale Reichweite in kurzer Zeit.</x-ui.alert>

    <x-ui.alert tone="info" title="Best Practice">Investieren Sie in 1-2 Featured-Wochen kurz vor Veranstaltungsbeginn
        für letzten Buchungsschub.</x-ui.alert>
</x-help.article>
