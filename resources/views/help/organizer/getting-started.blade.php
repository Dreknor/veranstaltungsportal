<x-help.article title="Erste Schritte als Organisator"
    subtitle="So richten Sie Ihre Organisation ein und starten mit dem Erstellen von Veranstaltungen." :back-href="route('help.category', 'organizer')"
    back-label="Zur Veranstalter-Hilfe">
    <section>
        <h2>1. Organisation auswählen oder erstellen</h2>
        <p>Gehen Sie im Organizer-Bereich zu „Organisation“ und wählen Sie eine bestehende Organisation aus oder
            erstellen Sie eine neue. Laden Sie ein Logo hoch und pflegen Sie die Beschreibung sowie Website und Kontakt.
        </p>
    </section>
    <section>
        <h2>2. Rechnungs- und Bankdaten hinterlegen</h2>
        <p>Unter „Kontoverbindung“ hinterlegen Sie Rechnungsadresse, USt-IdNr. und Bankverbindung. Diese Angaben sind
            notwendig für die automatisierte Rechnungsstellung und Auszahlungen.</p>
    </section>
    <section>
        <h2>3. Team einladen und Rollen vergeben</h2>
        <p>Laden Sie Kolleginnen und Kollegen ein, Rollen (z. B. „Editor“, „Finanzen“) vergeben und verwalten Sie
            Berechtigungen. So können mehrere Personen Veranstaltungen gemeinsam betreuen.</p>
    </section>
    <section>
        <h2>4. Erste Veranstaltung erstellen</h2>
        <p>Nutzen Sie „Veranstaltung anlegen“ und pflegen Sie Titel, Beschreibung, Kategorie sowie Format (Präsenz,
            Online oder Hybrid). Fügen Sie Ticket-Typen hinzu und veröffentlichen Sie die Veranstaltung, sobald alles
            vollständig ist.</p>
    </section>

    <x-ui.alert tone="info" title="Tipp">Für bessere Sichtbarkeit können Sie Ihre Veranstaltung als
        „Featured“ markieren und so prominent hervorheben.</x-ui.alert>
</x-help.article>
